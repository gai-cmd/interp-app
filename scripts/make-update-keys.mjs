// One-time setup of the extension's update signing keys (docs/extension.md §21):
//
//   node scripts/make-update-keys.mjs
//
// Creates TWO P-256 key pairs: the primary (signs every release) and a backup (kept offline: if the primary is ever
// lost or leaked, a release signed with the backup is still accepted by installed copies, and that release can then
// carry new public keys). The private keys are written to ~/.config/interp-app/ (mode 0600) and never printed. The
// public keys are written to extension/lib/update-keys.js, which is committed. Existing key files are never
// overwritten: the command stops with UPDATE_KEYS_EXIST instead.
import { mkdir, writeFile, access } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  DEFAULT_UPDATE_BACKUP_KEY_FILE, DEFAULT_UPDATE_KEY_FILE, UPDATE_KEY_DIR, generateUpdateKeyPair,
} from './update-signing.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const UPDATE_KEYS_MODULE = resolve(root, 'extension', 'lib', 'update-keys.js');

const exists = async (path) => { try { await access(path); return true; } catch { return false; } };

export function updateKeysSource(publicKeys) {
  return `// The public keys the extension trusts for its self-update (docs/extension.md §21): the primary signs every release,
// the backup stays offline. Both are SPKI DER, base64. The matching private keys are NOT in the repository
// (~/.config/interp-app/update-signing-*.pem). Generated by scripts/make-update-keys.mjs.
export const UPDATE_PUBLIC_KEYS = Object.freeze([
${publicKeys.map((key) => `  '${key}',`).join('\n')}
]);
`;
}

export async function makeUpdateKeys({
  keyDir = UPDATE_KEY_DIR, primaryFile = DEFAULT_UPDATE_KEY_FILE, backupFile = DEFAULT_UPDATE_BACKUP_KEY_FILE,
  publicOut = UPDATE_KEYS_MODULE, generate = generateUpdateKeyPair,
} = {}) {
  for (const path of [primaryFile, backupFile, publicOut]) {
    if (await exists(path)) throw Object.assign(new Error('UPDATE_KEYS_EXIST'), { code: 'UPDATE_KEYS_EXIST' });
  }
  const primary = generate();
  const backup = generate();
  await mkdir(keyDir, { recursive: true, mode: 0o700 });
  await writeFile(primaryFile, primary.privatePem, { mode: 0o600, flag: 'wx' });
  await writeFile(backupFile, backup.privatePem, { mode: 0o600, flag: 'wx' });
  await writeFile(publicOut, updateKeysSource([primary.publicB64, backup.publicB64]), { flag: 'wx' });
  return { primaryFile, backupFile, publicOut };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { primaryFile, backupFile, publicOut } = await makeUpdateKeys();
    console.log(`UPDATE_KEYS_OK primary=${primaryFile} backup=${backupFile} public=${publicOut}`);
    console.log('Back up BOTH .pem files somewhere safe and offline (the backup especially). They are not in git.');
  } catch (error) {
    console.error(error?.code ?? 'UPDATE_KEYS_FAILED');
    process.exitCode = 1;
  }
}
